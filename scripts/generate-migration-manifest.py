#!/usr/bin/env python3
"""Generate runtime-only version metadata from Goose SQL filenames."""
import argparse
import re
import subprocess
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--sql-dir', type=Path, default=Path('../../../migrations'))
parser.add_argument('--output', type=Path, default=Path('manifest_gen.go'))
args = parser.parse_args()
versions = {}
for path in sorted(args.sql_dir.glob('*.sql')):
    match = re.fullmatch(r'(\d+)_[a-z0-9_]+\.sql', path.name)
    if match is None:
        raise SystemExit('Invalid migration filename: ' + path.name)
    version = int(match.group(1))
    if version < 1 or version in versions:
        raise SystemExit('Invalid or duplicate migration version: ' + str(version))
    versions[version] = path.name
if not versions:
    raise SystemExit('No versioned SQL files found')
text = '// Code generated by generate-migration-manifest.py; DO NOT EDIT.\n\npackage dbschema\n\n'
text += '// Manifest returns the Goose migration versions required by this binary.\nfunc Manifest() []int64 {\nreturn []int64{\n'
for version in sorted(versions):
    text += f'{version},\n'
text += '}\n}\n'
result = subprocess.run(['gofmt'], input=text.encode(), stdout=subprocess.PIPE, check=True)
args.output.write_bytes(result.stdout)
